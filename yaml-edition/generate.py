def glass(radius=22, tint=58, inner=None):
    pane = GLASS % {"radius": radius, "tint": tint}
    return {"style": {".": pane, "mushroom-state-info$": inner}} if inner else {"style": pane}


def ladder(entity, area_id):
    """The same 65/68/78/84 ladder, as a Jinja chain — colour has to be
    computed by HA at render time, never baked in here."""
    if area_id in NO_COMFORT:
        return None
    table = FRIDGE_BANDS if area_id in COLD_AREAS else BANDS
    parts = [f"{{% set s = states('{entity}') %}}"]
    parts.append("{% if s in ['unavailable','unknown'] %}disabled{% else %}")
    parts.append("{% set t = s | float(0) %}")
    first = True
    for cut, color in table:
        if cut is None:
            parts.append(f"{{% else %}}{color}")
        else:
            parts.append(
                f"{{% {'if' if first else 'elif'} t < {cut} %}}{color}"
            )
            first = False
    parts.append("{% endif %}{% endif %}")
    return "".join(parts)


def hot_badge(entity, area_id):
    if area_id in NO_COMFORT:
        return None
    limit, icon = (50, "mdi:alert-circle") if area_id in COLD_AREAS else (84, "mdi:fire")
    return (
        f"{{% set s = states('{entity}') %}}"
        f"{{% if s not in ['unavailable','unknown'] and (s | float(0)) > {limit} %}}"
        f"{icon}{{% endif %}}"
    )


def room_section(area_id, area_name, entity, excluded):
    reading = {
        "type": "custom:mushroom-template-card",
        "entity": entity,
        "primary": (
            f"{{% set s = states('{entity}') %}}"
            "{% if s in ['unavailable','unknown'] %}—"
            f"{{% else %}}{{{{ s | float(0) | round(1) }}}}{UNIT}{{% endif %}}"
        ),
        "secondary": f"{{{{ state_attr('{entity}', 'summary') or 'no data' }}}}",
        "tap_action": {"action": "more-info"},
        "grid_options": {"columns": "full"},
        "card_mod": glass(inner=READING_CSS),
    }
    color = ladder(entity, area_id)
    if color:
        reading["icon_color"] = color
    badge = hot_badge(entity, area_id)
    if badge:
        reading["badge_icon"] = badge
        reading["badge_color"] = "red"

    def button(toggle, label, icon, on_color):
        return {
            "type": "custom:mushroom-template-card",
            "entity": toggle,
            "primary": label,
            "icon": (
                f"{{% if is_state('{toggle}','on') %}}mdi:eye-off-outline"
                f"{{% else %}}{icon}{{% endif %}}"
            ),
            "icon_color": (
                f"{{% if is_state('{toggle}','on') %}}grey"
                f"{{% else %}}{on_color}{{% endif %}}"
            ),
            "tap_action": {"action": "toggle"},
            "grid_options": {"columns": 6},
            "card_mod": glass(radius=999, tint=46, inner=PILL_CSS),
        }

    sensors_label = (
        f"{{% if is_state('{SENSORS_TOGGLE}','on') %}}Hide sensors{{% else %}}"
        f"{{{{ state_attr('{entity}','member_count') or 0 }}}} sensors{{% endif %}}"
    )
    offline_label = (
        f"{{% if is_state('{OFFLINE_TOGGLE}','on') %}}Hide offline{{% else %}}"
        f"{{{{ (state_attr('{entity}','offline') or []) | count }}}} offline{{% endif %}}"
    )

    # auto-entities keeps the member list live without any bespoke JS: it
    # re-filters on every state change, so a sensor added to this area shows
    # up here even though the dashboard config itself is a snapshot.
    def member_list(only_offline):
        include = [{"area": area_name, "device_class": DEVICE_CLASS}]
        if only_offline:
            include = [
                {"area": area_name, "device_class": DEVICE_CLASS, "state": s}
                for s in ("unavailable", "unknown")
            ]
        toggle = OFFLINE_TOGGLE if only_offline else SENSORS_TOGGLE
        for entry in include:
            entry["options"] = {
                "type": "tile",
                "state_content": ["state", "last_changed"],
                "card_mod": glass(radius=16, tint=40),
            }
        return {
            "type": "custom:auto-entities",
            "card": {"type": "grid", "columns": 1, "square": False},
            "card_param": "cards",
            "filter": {
                "include": include,
                "exclude": [{"entity_id": f"sensor.*{PREFIX}_average*"}]
                + [{"entity_id": e} for e in excluded]
                + ([{"state": "unavailable"}, {"state": "unknown"}] if not only_offline else []),
            },
            "sort": {"method": "friendly_name"},
            "show_empty": False,
            "grid_options": {"columns": "full"},
            "visibility": [
                {"condition": "state", "entity": toggle, "state": "on"}
            ],
        }

    cards = [
        {
            "type": "heading",
            "heading": area_name,
            "heading_style": "title",
        },
        reading,
        button(SENSORS_TOGGLE, sensors_label, "mdi:format-list-bulleted", "blue"),
        button(OFFLINE_TOGGLE, offline_label, "mdi:lan-disconnect", "orange"),
        member_list(False),
        member_list(True),
    ]
    return {"type": "grid", "cards": cards}


