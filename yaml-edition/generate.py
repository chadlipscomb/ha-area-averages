# ------------------------------------------------------------------ helpers


def slug(text: str) -> str:
    out = []
    for ch in str(text).lower():
        out.append(ch if ch.isalnum() else "_")
    while "__" in "".join(out):
        out = list("".join(out).replace("__", "_"))
    return "".join(out).strip("_")


def registries():
    """Registries plus the state machine — device_class is not in the registry
    list payload, it only exists on the live state."""
    areas, entities, devices = ws(
        [
            {"type": "config/area_registry/list"},
            {"type": "config/entity_registry/list"},
            {"type": "config/device_registry/list"},
        ]
    )
    states = {s["entity_id"]: s for s in rest("/api/states")}
    return (
        {a["area_id"]: a for a in areas},
        entities,
        {d["id"]: d for d in devices},
        states,
    )


def plan(areas, entities, devices, states):
    """Which areas get a sensor, which entities must be skipped, and the
    member list to hang state triggers on."""
    per_area: dict[str, list[str]] = {}
    skip: list[str] = []
    for entry in entities:
        entity_id = entry["entity_id"]
        if not entity_id.startswith("sensor."):
            continue
        state = states.get(entity_id)
        if not state or state["attributes"].get("device_class") != DEVICE_CLASS:
            continue
        # An average is not a member of itself. Catches the integration's
        # sensors and this twin's own on a regeneration.
        if entry.get("platform") == "area_averages":
            continue
        if state["attributes"].get("member_count") is not None:
            continue
        if entity_id.endswith("_yaml_average_temperature"):
            continue
        if entry.get("disabled_by"):
            continue
        # Jinja cannot read entity_category, so the diagnostic and config
        # entities the integration filters at runtime are baked in here.
        if entry.get("entity_category"):
            skip.append(entity_id)
            continue
        device = devices.get(entry.get("device_id") or "")
        area_id = entry.get("area_id") or (device or {}).get("area_id")
        if not area_id or area_id not in areas:
            continue
        per_area.setdefault(area_id, []).append(entity_id)
    return (
        {a: sorted(m) for a, m in sorted(per_area.items())},
        sorted(skip),
    )


def macro_text(skip: list[str]) -> str:
    return (
        MACRO.replace("__SKIP__", json.dumps(skip))
        .replace("__LABEL__", EXCLUDE_LABEL)
        .replace("__UNIT__", UNIT)
        .replace("__STALE__", str(STALE_HOURS))
        .replace("__BATT__", str(BATTERY_PCT))
        .replace("__CLASS__", DEVICE_CLASS)
    )


def yaml_list(items, indent):
    pad = " " * indent
    return "\n".join(f"{pad}- {i}" for i in items)


ATTRS = [
    "summary", "healthy", "member_count", "reporting", "minimum", "maximum",
    "spread", "issue", "issues", "sensors", "excluded", "offline", "stale",
    "low_battery",
]


def package_text(areas, per_area) -> str:
    out = [
        "# Area Averages — integration-free edition.",
        "#",
        "# GENERATED by yaml-edition/generate.py. Re-run it after adding an",
        "# area or a diagnostic temperature sensor; everything else (a sensor",
        "# moved into an area, an exclude-average label) is picked up live.",
        "#",
        "# Trigger-based on purpose: the action block computes the whole area",
        "# once into `data`, so the fourteen attributes below cost one pass",
        "# instead of fourteen. State triggers make it react instantly to the",
        "# sensors known at generation time; the one-minute tick is what",
        "# notices sensors that have appeared since.",
        "",
        "input_boolean:",
        f"  {PREFIX}_show_sensors:",
        "    name: YAML dashboard — show all sensors",
        "    icon: mdi:format-list-bulleted",
        f"  {PREFIX}_show_offline:",
        "    name: YAML dashboard — show offline sensors",
        "    icon: mdi:lan-disconnect",
        "",
        "template:",
    ]
    for area_id, members in per_area.items():
        name = areas[area_id]["name"]
        out += [
            f"  # ---------------------------------------------------- {name}",
            "  - trigger:",
            "      - trigger: state",
            "        entity_id:",
            yaml_list(members, 10),
            "      - trigger: time_pattern",
            '        minutes: "/1"',
            "      - trigger: homeassistant",
            "        event: start",
            "    action:",
            "      - variables:",
            "          data: >-",
            "            {% from 'area_average.jinja' import area_stats %}",
            f"            {{{{ area_stats('{area_id}') | from_json }}}}",
            "    sensor:",
            f'      - name: "{name} YAML Average Temperature"',
            f"        unique_id: {PREFIX}_avg_{slug(area_id)}_temperature",
            "        device_class: temperature",
            "        state_class: measurement",
            f'        unit_of_measurement: "{UNIT}"',
            "        availability: \"{{ data is defined }}\"",
            "        state: \"{{ data.mean if data.mean is not none else none }}\"",
            "        attributes:",
        ]
        for attr in ATTRS:
            out.append(f'          {attr}: "{{{{ data.{attr} }}}}"')
        out.append("")
    return "\n".join(out) + "\n"


