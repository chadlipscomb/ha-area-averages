def dashboard(areas, per_area, excluded_by_area):
    sections = [
        {
            "type": "grid",
            "column_span": 3,
            "cards": [
                {
                    "type": "markdown",
                    "content": STATUS.replace("%%", "%"),
                    "grid_options": {"columns": "full"},
                    "card_mod": glass(tint=52),
                }
            ],
        }
    ]
    for area_id in per_area:
        name = areas[area_id]["name"]
        entity = f"sensor.{slug(name)}_yaml_average_temperature"
        sections.append(
            room_section(area_id, name, entity, excluded_by_area.get(area_id, []))
        )
    return {
        "views": [
            {
                "title": "Rooms",
                "path": "rooms",
                "icon": "mdi:thermometer",
                "type": "sections",
                "max_columns": 3,
                "sections": sections,
            }
        ]
    }


def assign_areas(per_area):
    """Put each generated sensor in its area.

    The integration does this for its own entities; a YAML template sensor
    lands area-less, which breaks area_name() on the dashboard and keeps the
    sensor off area cards and out of voice assistants. Matched by unique_id,
    so a renamed entity_id does not break it, and only written when it would
    actually change.
    """
    entities = ws([{"type": "config/entity_registry/list"}])[0]
    by_unique = {
        e.get("unique_id"): e for e in entities if e.get("platform") == "template"
    }
    updates, already = [], 0
    for area_id in per_area:
        entry = by_unique.get(f"{PREFIX}_avg_{slug(area_id)}_temperature")
        if entry is None:
            print(f"  ! no entity yet for {area_id} — reload HA, then re-run")
            continue
        labels = sorted(set(entry.get("labels") or []) | {EXCLUDE_LABEL})
        if entry.get("area_id") == area_id and labels == sorted(entry.get("labels") or []):
            already += 1
            continue
        updates.append(
            {
                "type": "config/entity_registry/update",
                "entity_id": entry["entity_id"],
                "area_id": area_id,
                # Putting these sensors in an area makes the INTEGRATION treat
                # them as members of its own average — the exact mirror of the
                # loop this twin guards against internally. The integration is
                # not ours to change, so use the mechanism it already offers.
                "labels": labels,
            }
        )
    if updates:
        ws(updates)
    print(f"areas + exclude label: {len(updates)} written, {already} already correct")


def push_dashboard(config):
    existing = ws([{"type": "lovelace/dashboards/list"}])[0]
    if not any(d.get("url_path") == DASHBOARD_URL_PATH for d in existing):
        ws(
            [
                {
                    "type": "lovelace/dashboards/create",
                    "url_path": DASHBOARD_URL_PATH,
                    "title": DASHBOARD_TITLE,
                    "icon": DASHBOARD_ICON,
                    "show_in_sidebar": True,
                    "require_admin": False,
                }
            ]
        )
        print("dashboard created")
    ws(
        [
            {
                "type": "lovelace/config/save",
                "url_path": DASHBOARD_URL_PATH,
                "config": config,
            }
        ]
    )
    print(f"dashboard saved: /{DASHBOARD_URL_PATH}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--push", action="store_true", help="also push the dashboard")
    args = parser.parse_args()

    areas, entities, devices, states = registries()
    per_area, skip = plan(areas, entities, devices, states)

    label_map: dict[str, list[str]] = {}
    for entry in entities:
        if EXCLUDE_LABEL in (entry.get("labels") or []):
            device = devices.get(entry.get("device_id") or "")
            area_id = entry.get("area_id") or (device or {}).get("area_id")
            if area_id:
                label_map.setdefault(area_id, []).append(entry["entity_id"])

    (HERE / "custom_templates").mkdir(exist_ok=True)
    (HERE / "packages").mkdir(exist_ok=True)
    (HERE / "custom_templates" / "area_average.jinja").write_text(macro_text(skip))
    (HERE / "packages" / "area_averages_yaml.yaml").write_text(
        package_text(areas, per_area)
    )

    print(
        f"{len(per_area)} areas, "
        f"{sum(len(m) for m in per_area.values())} member sensors, "
        f"{len(skip)} diagnostic sensors skipped"
    )
    for area_id, members in per_area.items():
        print(f"  {areas[area_id]['name']:18} {len(members)} members")

    if args.push:
        assign_areas(per_area)
        push_dashboard(dashboard(areas, per_area, label_map))


