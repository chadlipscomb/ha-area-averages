#!/usr/bin/env python3
"""Generate the integration-free twin of Area Averages.

Emits, from the live registries:

  custom_templates/area_average.jinja   one macro, all the logic
  packages/area_averages_yaml.yaml      one trigger-based template sensor per
                                        area, plus the two reveal helpers
  (and, with --push, the "Area Temps (YAML)" dashboard)

Everything it produces is ordinary Home Assistant configuration — no
custom_components, no Python running inside HA. Stdlib only here too; the
websocket client is borrowed from ../tools/make_fixture.py.

    python3 yaml-edition/generate.py            # write the files
    python3 yaml-edition/generate.py --push     # ...and push the dashboard

Why anything is generated at all: a YAML template sensor cannot create
entities for areas it has not been told about, and Jinja cannot see an
entity's `entity_category`, so the diagnostic sensors the integration filters
out at runtime have to be baked in as a skip list. Membership *within* an
area stays live via area_entities(); only the set of areas and that skip list
are snapshots. Re-run this after adding an area or a diagnostic sensor.
"""

